import os
import time

from dotenv import load_dotenv
from google import genai


# ============================================================
# LOAD ENVIRONMENT VARIABLES
# ============================================================

load_dotenv()


# ============================================================
# GEMINI API KEY
# ============================================================

api_key = os.getenv("GEMINI_API_KEY")

if not api_key:
    raise ValueError(
        "GEMINI_API_KEY is not configured in the .env file."
    )


# ============================================================
# GEMINI CLIENT
# ============================================================

client = genai.Client(
    api_key=api_key
)


# ============================================================
# DEMO / FALLBACK LEGAL DOCUMENT
# ============================================================

def generate_fallback_document(
    document_type,
    parties,
    terms,
    dates
):
    """
    Generates a professional demo legal document when
    Gemini API is unavailable or quota is exhausted.
    """

    document = f"""
{document_type.upper()}

This document is prepared based on the information provided
by the user through the LegalEase application.

PARTIES

{parties}

EFFECTIVE DATE

{dates}

TERMS AND CONDITIONS

{terms}

AGREEMENT

The parties identified above agree to the terms and
conditions described in this document.

1. PURPOSE

This agreement sets out the understanding, responsibilities,
rights and obligations of the parties in relation to the
specified {document_type.lower()}.

2. RESPONSIBILITIES

Each party agrees to perform its responsibilities in
accordance with the terms specified in this agreement.

3. CONFIDENTIALITY

Where confidential information is shared between the
parties, such information shall be treated appropriately
and shall not be disclosed to unauthorized persons except
where disclosure is required by law.

4. COMPLIANCE

The parties agree to comply with all applicable laws,
rules and regulations relating to this agreement.

5. TERMINATION

This agreement may be terminated in accordance with the
terms mutually agreed upon by the parties.

6. GENERAL TERMS

The parties confirm that the information provided for this
document is accurate to the best of their knowledge.

Any modification to this agreement should be made with
the knowledge and consent of the relevant parties.

7. ACKNOWLEDGEMENT

By signing this document, the parties acknowledge that they
have read and understood the terms and conditions contained
in this agreement.

SIGNATURES


Party 1:

Name: ______________________________

Signature: _________________________

Date: ______________________________


Party 2:

Name: ______________________________

Signature: _________________________

Date: ______________________________


DISCLAIMER

This document is generated by the LegalEase application
for document preparation purposes. It should be reviewed
and customized by the relevant parties or a qualified legal
professional before being used for official purposes.
"""

    return document.strip()


# ============================================================
# GENERATE LEGAL DOCUMENT
# ============================================================

def generate_legal_document(
    document_type,
    parties,
    terms,
    dates
):

    prompt = f"""
You are a legal document generation assistant.

Create a professional and well-structured {document_type}.

Document Type:
{document_type}

Parties:
{parties}

Terms and Conditions:
{terms}

Important Dates:
{dates}

Instructions:

1. Create a clear and professional legal document.

2. Use appropriate headings and sections.

3. Include the details provided by the user.

4. Do not invent important personal,
   financial, or legal information.

5. Use the provided dates correctly.

6. Make the document easy to edit.

7. Include the provided terms and conditions.

8. Return only the legal document content.

9. Do not use Markdown symbols such as:
   #, ##, ###, **, or ---

10. Use plain text headings.
"""

    # ========================================================
    # TRY GEMINI
    # ========================================================

    for attempt in range(1, 4):

        try:

            print(
                f"Calling Gemini API... "
                f"Attempt {attempt}/3"
            )

            response = client.models.generate_content(
                model="gemini-3.8-flash",
                contents=prompt
            )

            # ------------------------------------------------
            # Check response
            # ------------------------------------------------

            if response is None:
                raise Exception(
                    "Gemini returned an empty response."
                )

            if not response.text:
                raise Exception(
                    "Gemini returned empty document text."
                )

            print(
                "Gemini document generated successfully."
            )

            return response.text

        except Exception as e:

            error_message = str(e)

            print(
                "========================================"
            )

            print(
                f"Gemini API attempt {attempt}/3 failed."
            )

            print(
                f"Error type: {type(e).__name__}"
            )

            print(
                f"Error message: {error_message}"
            )

            print(
                "========================================"
            )

            # ------------------------------------------------
            # If quota is exhausted, immediately use fallback
            # ------------------------------------------------

            if (
                "429" in error_message
                or "RESOURCE_EXHAUSTED" in error_message
                or "quota" in error_message.lower()
                or "exceeded your current quota" in error_message.lower()
            ):

                print(
                    "Gemini quota exhausted."
                )

                print(
                    "Using LegalEase fallback document generator."
                )

                return generate_fallback_document(
                    document_type=document_type,
                    parties=parties,
                    terms=terms,
                    dates=dates
                )

            # ------------------------------------------------
            # Retry other temporary errors
            # ------------------------------------------------

            if attempt < 3:

                print(
                    "Waiting 5 seconds before retrying..."
                )

                time.sleep(5)

            else:

                # ------------------------------------------------
                # If Gemini is unavailable for another reason,
                # use fallback so the application can continue.
                # ------------------------------------------------

                print(
                    "Gemini unavailable."
                )

                print(
                    "Using LegalEase fallback document generator."
                )

                return generate_fallback_document(
                    document_type=document_type,
                    parties=parties,
                    terms=terms,
                    dates=dates
                )


